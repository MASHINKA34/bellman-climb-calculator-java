package ru.mashinka.multiflow.core.network;

// встроенный пример: сеть из 7 вершин и 12 ветвей
// две группы вершин - {1, 3, 5} и {2, 4, 6, 7} - связаны между собой слабыми ветвями
// 1-2, 3-4, 5-6. Поэтому уже первый разрез делит сеть по этим ветвям, а на следующих
// шагах видно стягивание сразу нескольких вершин в одну
public final class Examples {

    private Examples() {
    }

    // каждый вызов отдаёт новую матрицу: правка копии не портит пример
    public static int[][] defaultNetwork() {
        return new int[][]{
                //1  2  3  4  5  6  7
                {0, 2, 9, 0, 7, 0, 0},  // 1
                {2, 0, 0, 7, 0, 5, 4},  // 2
                {9, 0, 0, 3, 8, 0, 0},  // 3
                {0, 7, 3, 0, 0, 6, 8},  // 4
                {7, 0, 8, 0, 0, 4, 0},  // 5
                {0, 5, 0, 6, 4, 0, 9},  // 6
                {0, 4, 0, 8, 0, 9, 0},  // 7
        };
    }
}
