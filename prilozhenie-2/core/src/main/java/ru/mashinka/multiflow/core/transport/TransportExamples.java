    public static int count() {
        return VARIANTS.length;
    }

    // вариант - с единицы, как в задании; каждый вызов отдаёт новые массивы
    public static TransportProblem variant(int number) {
        if (number < 1 || number > VARIANTS.length) {
            throw new IllegalArgumentException("Вариант должен быть от 1 до " + VARIANTS.length
                    + ", а задан " + number);
        }
        int[][] table = VARIANTS[number - 1];
        int m = table.length - 1;
        int n = table[m].length;
        int[][] cost = new int[m][n];
        int[] supply = new int[m];
        for (int i = 0; i < m; i++) {
            System.arraycopy(table[i], 0, cost[i], 0, n);
            supply[i] = table[i][n];
        }
        return TransportProblem.of(cost, supply, table[m]);
    }
