package ru.mashinka.multiflow.core.placement;

// встроенный пример - задача размещения производства из учебного пособия МЭСИ
// «Логистические модели», п. 3.2, пример 3.1: 3 новых вида продукции, 5 предприятий
//
// В пособии ошибка: в издержках производства на предприятии 5 напечатано 5 и 5
// (виды 1 и 2), прибыль на единицу посчитана по этим числам, а матрица для
// венгерского метода и ответ 7892 тыс. руб. - по числам 35 и 35. С напечатанными
// числами лучший ответ другой: 8137 тыс. руб. (вид 1 на предприятие 5).
// Здесь стоят 35 и 35: тогда весь пример сходится с книгой, от матрицы до ответа
// (вид 1 - предприятие 4, вид 2 - 1, вид 3 - 3, итого 7892 тыс. руб.).
public final class PlacementExamples {

    private PlacementExamples() {
    }

    // каждый вызов отдаёт новые массивы: правка копии не портит пример
    public static int[][] production() {
        return new int[][]{
                //1   2   3   4   5    предприятия
                {20, 23, 38, 15, 35},  // вид 1
                {8, 29, 6, 35, 35},    // вид 2
                {5, 8, 3, 4, 7},       // вид 3
        };
    }

    public static int[][] sales() {
        return new int[][]{
                {20, 50, 20, 10, 13},
                {7, 90, 8, 35, 60},
                {5, 5, 4, 15, 6},
        };
    }

    public static int[] volume() {
        return new int[]{35_000, 160_000, 54_000};
    }

    public static int[] price() {
        return new int[]{55, 50, 30};
    }

    public static PlacementProblem textbook() {
        return PlacementProblem.of(production(), sales(), volume(), price());
    }
}
